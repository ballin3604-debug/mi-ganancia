export function AppIcon({ name, size = 18, color = 'currentColor', strokeWidth = 2, className = '' }) {
  const entry = ICONS[name];
  if (!entry) return null;
  const { Component } = entry;
  return (
    <Component
      size={size}
      color={color}
      strokeWidth={strokeWidth}
      className={`shrink-0 ${className}`}
    />
  );
}

